function url(path, name, key) {
  const fallback = DEFAULTS[key];
  const finalPath = path || fallback;
  if (!finalPath) {
    console.error(`[config] ${name} is missing. Add it to .env`);
    return BASE;
  }
  return BASE + finalPath;
}

